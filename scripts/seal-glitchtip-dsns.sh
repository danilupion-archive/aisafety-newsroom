#!/usr/bin/env bash
# Seals the GlitchTip DSN of each aisafety-newsroom component (api, worker, web) for the cluster into a gitops checkout
# (SPEC §15). Nothing secret is printed or written unencrypted: each DSN is read with hidden input and reaches kubectl
# through /dev/fd (process substitution), never through argv or a file. The cluster, the gitops layout and the error
# tracker's in-cluster host come from scripts/ops.env.
#
# Usage: scripts/seal-glitchtip-dsns.sh <path-to-gitops>
# Paste each project's DSN from GlitchTip (project settings, Client Keys). The host is rewritten to the in-cluster one
# (ERROR_TRACKING_HOST): the apps report inside the cluster, whatever host GlitchTip's UI shows. Refuses to overwrite:
# to rotate, delete the files first.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
# shellcheck source-path=SCRIPTDIR source=lib/ops-env.sh
. "$(dirname "$0")/lib/ops-env.sh"
ops_env_require GITOPS_APP_SECRETS_DIR ERROR_TRACKING_HOST
ops_env_kubeseal_args

APP_DIR="$GITOPS/$GITOPS_APP_SECRETS_DIR"
APPS=(api worker web)

[ -d "$APP_DIR" ] || { echo "Not a gitops checkout with aisafety-newsroom secrets: $APP_DIR is missing" >&2; exit 1; }
for app in "${APPS[@]}"; do
  if [ -e "$APP_DIR/aisafety-newsroom-$app-glitchtip.yaml" ]; then
    echo "Refusing to overwrite $APP_DIR/aisafety-newsroom-$app-glitchtip.yaml" >&2
    exit 1
  fi
done

for app in "${APPS[@]}"; do
  printf 'GlitchTip DSN of project aisafety-newsroom-%s: ' "$app"
  IFS= read -rs dsn
  echo
  # https://<key>@<any host>/<project> becomes http://<key>@<in-cluster host>/<project>.
  if [[ ! "$dsn" =~ ^https?://([0-9A-Fa-f-]+)@[^/@]+/([0-9]+)/?$ ]]; then
    echo "That is not a GlitchTip DSN (expected https://<key>@<host>/<project>); nothing written for $app" >&2
    exit 1
  fi
  internal="http://${BASH_REMATCH[1]}@$ERROR_TRACKING_HOST/${BASH_REMATCH[2]}"
  out="$APP_DIR/aisafety-newsroom-$app-glitchtip.yaml"
  tmp="$out.tmp"
  # Sync wave -2, like the other aisafety-newsroom secrets: created before the Deployments (wave 0).
  if ! {
    printf '# yamllint disable rule:line-length\n'
    printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
    printf '# SENTRY_DSN for aisafety-newsroom-%s: GlitchTip project aisafety-newsroom-%s, through the in-cluster host.\n' \
      "$app" "$app"
    printf '# Generated by scripts/seal-glitchtip-dsns.sh in danilupion/aisafety-newsroom.\n'
    kubectl create secret generic "aisafety-newsroom-$app-glitchtip" -n aisafety-newsroom \
      --from-file=SENTRY_DSN=<(printf %s "$internal") --dry-run=client -o yaml \
      | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
      | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
  } >"$tmp"; then
    rm -f "$tmp"
    echo "Failed to seal $out" >&2
    exit 1
  fi
  mv "$tmp" "$out"
  echo "sealed $out"
done
unset dsn internal
