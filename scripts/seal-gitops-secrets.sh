#!/usr/bin/env bash
# Generates the newsroom database passwords and the API token, and seals every aisafety-newsroom secret for the
# cluster into a gitops checkout (SPEC §14, §15). Nothing secret is printed or written unencrypted: secrets live in
# shell variables and reach kubectl through /dev/fd (process substitution), never through argv or a file. The API
# token is also stored in the macOS Keychain, for tools/newsroom.py in aisafety-media (R-MED-1). The cluster, the
# gitops layout and the registry come from scripts/ops.env (scripts/lib/ops-env.sh).
#
# Usage: scripts/seal-gitops-secrets.sh <path-to-gitops>
# Run it in a terminal: it asks for the registry secret of the pull robot (input hidden). Refuses to overwrite: to
# rotate, delete the files first. The three passwords are always generated together, and the database's provisioning
# hook applies them to the roles on its next sync, so commit them with the database's entry in gitops, never before
# or after it.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
# shellcheck source-path=SCRIPTDIR source=lib/ops-env.sh
. "$(dirname "$0")/lib/ops-env.sh"
ops_env_require GITOPS_APP_SECRETS_DIR GITOPS_DB_SECRETS_DIR DB_NAMESPACE DB_HOST REGISTRY REGISTRY_PULL_ROBOT \
  REGISTRY_PULL_SECRET
ops_env_kubeseal_args
# Where the API token goes in the Keychain (R-MED-1). KEYCHAIN=skip leaves it out.
KEYCHAIN_SERVICE=aisafety-newsroom
KEYCHAIN_ACCOUNT=api-token

PG_DIR="$GITOPS/$GITOPS_DB_SECRETS_DIR"
APP_DIR="$GITOPS/$GITOPS_APP_SECRETS_DIR"
NAMESPACE=aisafety-newsroom

files=("$PG_DIR/newsroom-db-credentials.yaml" "$APP_DIR/$REGISTRY_PULL_SECRET.yaml"
  "$APP_DIR/aisafety-newsroom-owner-db.yaml" "$APP_DIR/aisafety-newsroom-app-db.yaml"
  "$APP_DIR/aisafety-newsroom-public-db.yaml" "$APP_DIR/aisafety-newsroom-api-token.yaml")
for f in "${files[@]}"; do
  if [ -e "$f" ]; then
    echo "Refusing to overwrite $f" >&2
    exit 1
  fi
done
[ -d "$PG_DIR" ] || { echo "Not a gitops checkout: $PG_DIR is missing" >&2; exit 1; }
if [ "${KEYCHAIN:-}" != skip ] && ! command -v security >/dev/null; then
  echo "No macOS Keychain here: run with KEYCHAIN=skip, and read the API token from the cluster later" >&2
  exit 1
fi
mkdir -p "$APP_DIR"

# seal <out> <header> <wave|-> <kubectl create secret args...>
# Writes header comments plus the SealedSecret. Secrets in the app namespace get sync wave -2, so Argo CD creates them
# before the migration Job (wave -1) and the Deployments (wave 0).
seal() {
  local out="$1" header="$2" wave="$3"
  shift 3
  local tmp="$out.tmp"
  if ! {
    printf '# yamllint disable rule:line-length\n'
    printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
    printf '%s\n' "$header"
    kubectl create secret "$@" --dry-run=client -o yaml \
      | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
      | if [ "$wave" = - ]; then sed '/^---$/d'; else
          kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=$wave" -o yaml
        fi
  } >"$tmp"; then
    rm -f "$tmp"
    echo "Failed to seal $out" >&2
    exit 1
  fi
  mv "$tmp" "$out"
  echo "sealed $out"
}

printf 'Registry secret for %s: ' "$REGISTRY_PULL_ROBOT"
IFS= read -rs REGISTRY_SECRET
echo
[ -n "$REGISTRY_SECRET" ] || { echo "Empty registry secret" >&2; exit 1; }

owner_pw="$(openssl rand -hex 32)"
app_pw="$(openssl rand -hex 32)"
public_pw="$(openssl rand -hex 32)"
# 256 bits (R-API-2): 64 hex characters, over the API's minimum of 43.
api_token="$(openssl rand -hex 32)"
url() { printf 'postgres://%s:%s@%s/newsroom?sslmode=disable' "$1" "$2" "$DB_HOST"; }

seal "$PG_DIR/newsroom-db-credentials.yaml" \
  "# Read by the database's provisioning hook: owner and extra-role passwords for the newsroom database
# (openssl rand -hex 32 each). Each must match DATABASE_URL in aisafety-newsroom/aisafety-newsroom-<role>-db.
# Generated by scripts/seal-gitops-secrets.sh in danilupion/aisafety-newsroom." - \
  generic newsroom-db-credentials -n "$DB_NAMESPACE" \
  --from-file=NEWSROOM_OWNER_PASSWORD=<(printf %s "$owner_pw") \
  --from-file=NEWSROOM_APP_PASSWORD=<(printf %s "$app_pw") \
  --from-file=NEWSROOM_PUBLIC_PASSWORD=<(printf %s "$public_pw")

seal "$APP_DIR/$REGISTRY_PULL_SECRET.yaml" \
  "# Pull secret for $REGISTRY/aisafety-newsroom ($REGISTRY_PULL_ROBOT, pull only), on the default SA." -2 \
  generic "$REGISTRY_PULL_SECRET" -n "$NAMESPACE" --type=kubernetes.io/dockerconfigjson \
  --from-file=.dockerconfigjson=<(REGISTRY="$REGISTRY" REGISTRY_PULL_ROBOT="$REGISTRY_PULL_ROBOT" \
    REGISTRY_SECRET="$REGISTRY_SECRET" jq -cn '
    {auths: {(env.REGISTRY): {username: env.REGISTRY_PULL_ROBOT, password: env.REGISTRY_SECRET,
      auth: ("\(env.REGISTRY_PULL_ROBOT):\(env.REGISTRY_SECRET)" | @base64)}}}')

seal "$APP_DIR/aisafety-newsroom-owner-db.yaml" \
  "# DATABASE_URL for newsroom_owner (migrations only): $(url newsroom_owner '<OWNER_PASSWORD>')" -2 \
  generic aisafety-newsroom-owner-db -n "$NAMESPACE" --from-file=DATABASE_URL=<(url newsroom_owner "$owner_pw")

seal "$APP_DIR/aisafety-newsroom-app-db.yaml" \
  "# DATABASE_URL for newsroom_app (the API and the worker): $(url newsroom_app '<APP_PASSWORD>')" -2 \
  generic aisafety-newsroom-app-db -n "$NAMESPACE" --from-file=DATABASE_URL=<(url newsroom_app "$app_pw")

seal "$APP_DIR/aisafety-newsroom-public-db.yaml" \
  "# DATABASE_URL for newsroom_public (the API's public read routes): $(url newsroom_public '<PUBLIC_PASSWORD>')" -2 \
  generic aisafety-newsroom-public-db -n "$NAMESPACE" --from-file=DATABASE_URL=<(url newsroom_public "$public_pw")

seal "$APP_DIR/aisafety-newsroom-api-token.yaml" \
  "# API_TOKEN: the bearer token for /api/v1 (R-API-2; openssl rand -hex 32). aisafety-media keeps it in the Keychain." \
  -2 generic aisafety-newsroom-api-token -n "$NAMESPACE" --from-file=API_TOKEN=<(printf %s "$api_token")

if [ "${KEYCHAIN:-}" != skip ]; then
  # Through security's own prompt mode, which reads the command from stdin: the token never reaches argv.
  printf 'add-generic-password -U -s %s -a %s -l "aisafety-newsroom API token" -w %s\n' \
    "$KEYCHAIN_SERVICE" "$KEYCHAIN_ACCOUNT" "$api_token" | security -i >/dev/null
  echo "stored the API token in the Keychain (service $KEYCHAIN_SERVICE, account $KEYCHAIN_ACCOUNT)"
fi

unset REGISTRY_SECRET owner_pw app_pw public_pw api_token
echo "Done. Review with: git -C \"$GITOPS\" status"
